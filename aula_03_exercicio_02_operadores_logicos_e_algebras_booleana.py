  #Operadores Lógicos e Álgebra Booleana
   #Operadores Booleanos (and, or,not)
#------------------------------
# 1. Operador not
#------------------------------
print("---TESTE OPERADOR: not ---")
x = True
y = False
print(not x)
print(not y)

#------------------------------
# 2. Operador and - Retorna True se ambos os valores forem True
#------------------------------
print("---TESTE OPERADOR: and ---")
x = False
y = True
print(x and y)

#------------------------------
# 3. Operador or - Retorna True se pelo menos um dos valores for True 
#------------------------------
print("---TESTE OPERADOR: or ---")
x = False
y = False
print(x or y)